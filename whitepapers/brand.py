# ------------------------------------------------- the fifteen-mission spectrum
#
# "Ultraviolet to lime through azure, cyan and spring — enough hue travelled that any
#  two adjacent missions are visibly different. Position on the sweep is the meaning."
#
# Generated by interpolating OKLCH from ultraviolet (L .438 C .266 H 272.6) to lime
# (L .904 C .192 H 121.8) across fifteen stops. The arc passes through azure at
# stop 4, cyan at stop 7 and spring at stop 11, which is the sweep the presentation
# describes — the hues were not chosen, they fell out of the two endpoints.

MISSION_SPECTRUM = [
    "#3418E0", "#003EE9", "#005AEE", "#0071ED", "#0087E8",
    "#009AE0", "#00ABD4", "#00BAC6", "#00C8B6", "#00D3A4",
    "#00DC91", "#00E47E", "#6CEA6B", "#A1EE58", "#CBF24A",
]

# Contrast against white falls below 3:1 from stop 6 onward and below 2:1 from stop
# 10. The ribbon that carries this sweep is an identity device, always labelled, and
# never the sole carrier of a value.
SPECTRUM_SAFE_ON_WHITE = 5   # stops 1-5 clear 3:1 unaided

