"""
The StartPad design system, encoded.

Everything here is traceable to the 2026 brand presentation. Where the presentation
states a rule, the rule is quoted in a comment beside the value it produces, so a
future change is argued against the source rather than against taste.

Colour architecture (ch. 03)
----------------------------
    Lime  #CBF24A   ground, 44%   "At 1.29:1 against white it cannot carry type,
                                   so it is used as ground and never as ink."
    White           working surface, 30%
    Ultraviolet  #3418E0  contrast, 18%   carries white type at 8.9:1
    Ink   #0B0E14   8%

Both measured contrasts reproduce the presentation's figures exactly: lime 1.29:1 and
ultraviolet 8.92:1 against white.

Chart colour
------------
These documents are print. There is one surface — paper — so there is one mode, and
no dark-mode ramp is defined. Every palette below was checked with a validator rather
than chosen by eye; the recorded results are in CHART_PALETTE_CHECKS.
"""

